function sheetXml({ title = [], header = [], rows = [] }) {
  let r = 0; const out = [];
  const cell = (v, ci, s) => {
    const ref = `${colName(ci)}${r}`;
    if (typeof v === "number" && Number.isFinite(v)) return `<c r="${ref}" s="${s}"><v>${v}</v></c>`;
    return `<c r="${ref}" s="${s}" t="inlineStr"><is><t xml:space="preserve">${x(v)}</t></is></c>`;
  };
  title.forEach((line, i) => { r += 1; out.push(`<row r="${r}">${(Array.isArray(line) ? line : [line]).map((v, ci) => cell(v, ci, i === 0 ? 3 : ci === 0 ? 4 : 0)).join("")}</row>`); });
  if (title.length) r += 1;
  let headRow = 0;
  if (header.length) { r += 1; headRow = r; out.push(`<row r="${r}">${header.map((v, ci) => cell(v, ci, 1)).join("")}</row>`); }
  rows.forEach((row) => { r += 1; out.push(`<row r="${r}">${row.map((v, ci) => cell(v, ci, 2)).join("")}</row>`); });
  const widths = header.map((h, ci) => Math.min(48, Math.max(9, String(h).length + 2, ...rows.slice(0, 200).map((row) => String(row[ci] ?? "").length + 2))));
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
${headRow ? `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${headRow}" topLeftCell="A${headRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` : ""}
${widths.length ? `<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join("")}</cols>` : ""}
<sheetData>${out.join("")}</sheetData>
${headRow && rows.length ? `<autoFilter ref="A${headRow}:${colName(header.length - 1)}${headRow + rows.length}"/>` : ""}
</worksheet>`;
}

/** sheets: [{ name, title?: [string | string[]], header: string[], rows: any[][] }] → Blob (.xlsx) */
export function makeXlsx(sheets) {
  const names = sheets.map((s, i) => safeSheet(s.name, i));
  const files = [
    { name: "[Content_Types].xml", data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>${sheets.map((_, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join("")}</Types>` },
    { name: "_rels/.rels", data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>` },
    { name: "xl/workbook.xml", data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>${names.map((n, i) => `<sheet name="${x(n)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`).join("")}</sheets></workbook>` },
    { name: "xl/_rels/workbook.xml.rels", data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${sheets.map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`).join("")}<Relationship Id="rId${sheets.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>` },
    { name: "xl/styles.xml", data: STYLES },
    ...sheets.map((s, i) => ({ name: `xl/worksheets/sheet${i + 1}.xml`, data: sheetXml(s) })),
  ];
  return makeZip(files, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
}

export function saveBlob(blob, fileName) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob); a.download = fileName; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 1500);
}
